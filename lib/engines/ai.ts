const WRITE_TOOLS = new Set(Object.keys(INSTRUCTIONS).concat(['word-counter']));

const LENGTH_WORDS: Record<string, number> = { short: 150, medium: 400, long: 900 };

const SYSTEM =
  'You are a senior editor and copywriter. You follow the requested format exactly, ' +
  'write in plain confident English, never invent facts about real people or companies, ' +
  'and never wrap the answer in code fences or add a preamble.';

export function isWriteRoute(route: string) {
  return WRITE_TOOLS.has(route);
}

function countWords(ctx: EngineCtx): EngineOutput[] {
  const text = (ctx.params.text ?? '').trim();
  if (!text) throw new UserError('Paste the text you want to count.');
  const words = text.split(/\s+/).filter(Boolean);
  const sentences = text.split(/[.!?]+(?:\s|$)/).filter((s) => s.trim()).length;
  const paragraphs = text.split(/\n\s*\n/).filter((p) => p.trim()).length;
  const lines = [
    `Characters (with spaces): ${text.length}`,
    `Characters (no spaces):   ${text.replace(/\s/g, '').length}`,
    `Words:                    ${words.length}`,
    `Sentences:                ${sentences}`,
    `Paragraphs:               ${paragraphs}`,
    `Unique words:             ${new Set(words.map((w) => w.toLowerCase().replace(/[^\p{L}\p{N}']/gu, ''))).size}`,
    `Average word length:      ${(words.join('').length / Math.max(1, words.length)).toFixed(2)}`,
    `Reading time:             ${Math.max(1, Math.round(words.length / 220))} min at 220 wpm`,
    `Speaking time:            ${Math.max(1, Math.round(words.length / 130))} min at 130 wpm`,
  ];
  return [{ name: 'word-count.txt', mime: 'text/plain; charset=utf-8', buffer: Buffer.from(lines.join('\n') + '\n', 'utf8') }];
}

function buildPrompt(route: string, params: Record<string, string>, text: string): string {
  const parts: string[] = [INSTRUCTIONS[route] ?? 'Improve the text below.'];
  const tone = (params.tone ?? '').trim();
  const length = (params.length ?? 'medium').trim();
  if (route === 'translate') parts.push(`Target language: ${(params.language ?? 'English').trim()}.`);
  if (tone) parts.push(`Tone: ${tone}.`);
  const words = LENGTH_WORDS[length] ?? LENGTH_WORDS.medium;
  parts.push(`Target length: about ${words} words.`);
  if ((params.audience ?? '').trim()) parts.push(`Audience: ${params.audience.trim()}.`);
  if ((params.keywords ?? '').trim()) parts.push(`Work in these keywords naturally: ${params.keywords.trim()}.`);
  const count = Number(params.count ?? 0);
  if (Number.isFinite(count) && count > 0) parts.push(`Produce exactly ${Math.min(20, count)} items.`);
  parts.push('Return only the finished output — no preamble, no notes, no code fences.');
  parts.push(`\nInput:\n"""\n${text}\n"""`);
  return parts.join('\n');
}

function aiMessage(err: unknown): UserError {
  if (err instanceof AiUnavailableError) return new UserError(err.message);
  return new UserError(`The AI request failed: ${(err as Error).message}`);
}

/** All write/* tools: prompt-driven text generation. */
export const write = async (ctx: EngineCtx): Promise<EngineOutput[]> => {
  const route = ctx.fixed.route ?? '';
  if (route === 'word-counter') return countWords(ctx);

  const text = (ctx.params.text ?? '').trim();
  if (!text) throw new UserError('Type or paste the text this tool should work on.');
  if (text.length > 20000) throw new UserError('That is over 20,000 characters. Trim it down for this tool.');

  ctx.progress(20, 'Thinking');
  let result;
  try {
    result = await generateText([{ role: 'user', content: buildPrompt(route, ctx.params, text) }], {
      system: SYSTEM,
      temperature: route === 'grammar-fixer' || route === 'translate' ? 0.2 : 0.75,
      maxTokens: 2000,
    });
  } catch (err) {
    throw aiMessage(err);
  }
  ctx.progress(90, `Written by ${result.provider}/${result.model}`);

  let out = result.text.trim();
  if (route === 'ai-detector') {
    out += '\n\n---\nDisclaimer: this is a language-model estimate, not a forensic result. ' +
      'AI detectors are unreliable in both directions; use it as a signal only.\n';
  }
  return [{
    name: `${route}.txt`,
    mime: 'text/plain; charset=utf-8',
    buffer: Buffer.from(out + '\n', 'utf8'),
  }];
};

