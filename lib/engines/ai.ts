async function pdfText(filePath: string): Promise<string> {
  const pdfjs = await import('pdfjs-dist/legacy/build/pdf.mjs');
  const data = new Uint8Array(await fs.readFile(filePath));
  const doc = await pdfjs.getDocument({ data, isEvalSupported: false, useSystemFonts: true }).promise;
  const pages: string[] = [];
  for (let p = 1; p <= doc.numPages; p++) {
    const page = await doc.getPage(p);
    const content = await page.getTextContent();
    pages.push(content.items.map((i) => ('str' in i ? i.str : '')).join(' ').replace(/\s+/g, ' ').trim());
  }
  await doc.destroy();
  return pages.join('\n\n').trim();
}

function chunks(text: string, size = 9000, max = 6): string[] {
  const out: string[] = [];
  let i = 0;
  while (i < text.length && out.length < max) {
    let end = Math.min(text.length, i + size);
    if (end < text.length) {
      const stop = text.lastIndexOf('. ', end);
      if (stop > i + size / 2) end = stop + 1;
    }
    out.push(text.slice(i, end));
    i = end;
  }
  return out;
}

function wrap(text: string, width: number): string[] {
  const lines: string[] = [];
  for (const rawLine of text.split('\n')) {
    if (!rawLine.trim()) { lines.push(''); continue; }
    let line = '';
    for (const word of rawLine.split(/\s+/)) {
      if ((line + ' ' + word).trim().length > width && line) {
        lines.push(line.trim());
        line = word;
      } else {
        line = `${line} ${word}`.trim();
      }
    }
    if (line) lines.push(line.trim());
  }
  return lines;
}

async function textPdf(text: string, title: string): Promise<Buffer> {
  const doc = await PDFDocument.create();
  const font = await doc.embedFont(StandardFonts.Helvetica);
  const bold = await doc.embedFont(StandardFonts.HelveticaBold);
  const safe = (s: string) => s.replace(/[^\x20-\x7E\n]/g, ' ');
  let page = doc.addPage([595, 842]);
  let y = 800;
  page.drawText(safe(title).slice(0, 80), { x: 50, y, size: 15, font: bold });
  y -= 26;
  for (const line of wrap(safe(text), 92)) {
    if (y < 60) { page = doc.addPage([595, 842]); y = 800; }
    page.drawText(line, { x: 50, y, size: 10.5, font });
    y -= 15;
  }
  return Buffer.from(await doc.save());
}

export const pdfTool = async (ctx: EngineCtx): Promise<EngineOutput[]> => {
  const op = ctx.fixed.op ?? 'summarize';
  const file = ctx.files[0];
  if (!file) throw new UserError('Add a PDF.');

  ctx.progress(8, 'Reading the text layer');
  const text = await pdfText(file.path);
  if (!text.trim()) throw new UserError('This PDF has no text layer (it looks scanned). OCR it first.');

  const parts = chunks(text);
  const results: string[] = [];
  for (let i = 0; i < parts.length; i++) {
    ctx.progress(15 + Math.round((i / parts.length) * 70), `Part ${i + 1} of ${parts.length}`);
    const instruction = op === 'translate'
      ? `Translate the following document text into ${(ctx.params.language ?? 'English').trim()}. Keep headings, lists and numbers intact. Return only the translation.`
      : i === 0
        ? 'Summarise this part of a document: 2-4 sentences plus 3 bullet key points. Return only the summary.'
        : 'Summarise this part of a document concisely: 2-3 sentences plus at most 3 bullets.';
    try {
      const r = await generateText([{ role: 'user', content: `${instruction}\n\n"""\n${parts[i]}\n"""` }], {
        system: SYSTEM,
        temperature: 0.3,
        maxTokens: 1400,
      });
      results.push(r.text.trim());
    } catch (err) {
      throw aiMessage(err);
    }
  }

  let body = results.join('\n\n');
  if (op === 'summarize' && parts.length > 1) {
    try {
      const final = await generateText(
        [{ role: 'user', content: `Merge these partial summaries into one coherent summary: a TL;DR, then 5 bullets.\n\n${body}` }],
        { system: SYSTEM, temperature: 0.3, maxTokens: 1200 },
      );
      body = final.text.trim();
    } catch {
      /* keep the per-part summaries */
    }
  }

  const base = baseName(file.name);
  if (op === 'translate') {
    return [
      { name: `${base}-translated.pdf`, mime: 'application/pdf', buffer: await textPdf(body, `${base} (translated)`) },
      { name: `${base}-translated.txt`, mime: 'text/plain; charset=utf-8', buffer: Buffer.from(body + '\n', 'utf8') },
    ];
  }
  return [{ name: `${base}-summary.txt`, mime: 'text/plain; charset=utf-8', buffer: Buffer.from(body + '\n', 'utf8') }];
};
